"""Turn the astronomical reference into compact data embedded in both libraries.

Inputs : reference/nowruz.json   (from scripts/equinox.py + scripts/build_reference.py)
         reference/tehran-tz.json (Asia/Tehran UTC-offset transitions, from IANA tzdata)
Outputs: js/src/data.ts, python/src/taqvim/_data.py, reference/nowruz.csv
"""
import json, datetime as dt, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
ref = json.load(open(root / 'reference' / 'nowruz.json'))
tz = json.load(open(root / 'reference' / 'tehran-tz.json'))
EPOCH = dt.date(1970, 1, 1)

first = ref[0]['jy']
last = ref[-1]['jy']
bits = 0
for r in ref:
    if r['leap']:
        bits |= 1 << (r['jy'] - first)
nbytes = (last - first + 1 + 7) // 8
leap_hex = bits.to_bytes(nbytes, 'little').hex()
nowruz1 = (dt.date.fromisoformat(ref[0]['nowruz']) - EPOCH).days
uncertain = [r['jy'] for r in ref if r['uncertain']]
tz_initial = tz[0][1]
tz_trans = [[t // 1000, o] for t, o in tz[1:]]

header = 'Generated by scripts/generate_data.py, do not edit by hand.'
ts = f"""// {header}
/** First and last Solar Hijri years covered by the astronomical table. */
export const MIN_YEAR = {first};
export const MAX_YEAR = {last};
/** Days since 1970-01-01 (proleptic Gregorian) of 1 Farvardin of MIN_YEAR. */
export const NOWRUZ_EPOCH_DAY = {nowruz1};
/** Little-endian bitmap: bit (year - MIN_YEAR) is set when the year has 366 days. */
export const LEAP_HEX = '{leap_hex}';
/** Years whose Nowruz depends on the noon convention or lies within the ephemeris error margin. */
export const UNCERTAIN_YEARS: readonly number[] = {json.dumps(uncertain)};
/** Asia/Tehran: UTC offset in minutes before the first transition. */
export const TEHRAN_INITIAL_OFFSET = {tz_initial};
/** Asia/Tehran transitions: [unix seconds, UTC offset in minutes from that instant]. */
export const TEHRAN_TRANSITIONS: readonly (readonly [number, number])[] = {json.dumps(tz_trans)};
"""
(root / 'js' / 'src' / 'data.ts').write_text(ts)
py = f'''# {header}
MIN_YEAR = {first}
MAX_YEAR = {last}
NOWRUZ_EPOCH_DAY = {nowruz1}  # days since 1970-01-01 of 1 Farvardin of MIN_YEAR
LEAP_HEX = '{leap_hex}'
UNCERTAIN_YEARS = frozenset({json.dumps(uncertain)})
TEHRAN_INITIAL_OFFSET = {tz_initial}
TEHRAN_TRANSITIONS = {json.dumps(tz_trans)}
'''
(root / 'python' / 'src' / 'taqvim' / '_data.py').write_text(py)
with open(root / 'reference' / 'nowruz.csv', 'w') as f:
    f.write('jalali_year,nowruz_gregorian,leap,uncertain,equinox_utc\n')
    for r in ref:
        f.write(f"{r['jy']},{r['nowruz']},{int(r['leap'])},{int(r['uncertain'])},{r['equinox_utc']}\n")
print('years', first, last, 'leap bytes', nbytes, 'uncertain', len(uncertain), 'tz transitions', len(tz_trans))
